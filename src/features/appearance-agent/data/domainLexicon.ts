const IN_DOMAIN_TERMS = [...HAIR_TERMS, ...OUTFIT_TERMS, ...SCENE_TERMS, ...APPEARANCE_GOAL_TERMS];

function findMatches(text: string, terms: string[]): string[] {
  const lower = text.toLowerCase();
  return terms.filter((t) => lower.includes(t.toLowerCase()));
}

/**
 * 第一层审核。红线判定优先于领域判定——「把我的下巴削尖，再配个碎盖」既在范畴内
 * 也命中红线，必须判为 blocked。
 */
export function reviewFreeInput(text: string): LexiconVerdict {
  // 1. 无歧义词，直接阻断
  for (const [category, terms] of Object.entries(ALWAYS_BLOCKED) as [BlockedCategory, string[]][]) {
    const hits = findMatches(text, terms);
    if (hits.length > 0) return { kind: "blocked", category, matchedTerms: hits };
  }

  // 2. 敏感部位 × 物理改变动词共现。若同时出现视觉修饰词，视为正当请求不阻断。
  const isVisualOnly = findMatches(text, VISUAL_EFFECT_ONLY).length > 0;
  if (!isVisualOnly) {
    const alterationHits = findMatches(text, PHYSICAL_ALTERATION);
    if (alterationHits.length > 0) {
      for (const [category, parts] of Object.entries(SENSITIVE_PARTS) as [BlockedCategory, string[]][]) {
        const partHits = findMatches(text, parts);
        if (partHits.length > 0) {
          return { kind: "blocked", category, matchedTerms: [...partHits, ...alterationHits] };
        }
      }
    }
  }

  // 3. 领域判定
  const domainHits = findMatches(text, IN_DOMAIN_TERMS);
  if (domainHits.length === 0) return { kind: "out_of_domain" };
  return { kind: "in_domain", matchedTerms: domainHits };
}

