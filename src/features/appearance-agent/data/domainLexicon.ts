/**
 * 自由输入审核的第一层：确定性词库匹配。
 *
 * 用户在「有没有中意的发型/穿搭风格」环节可以自由输入。这段文本会被用来
 * 驱动 img2img 生成，所以不能直接透传。审核分两层：
 *
 *   第一层（本文件，确定性）：判断输入是否落在发型/穿搭范畴内，以及是否命中红线
 *   第二层（LLM）：对通过第一层的输入做越界与合适度判断
 *
 * 设计原则：红线是**硬编码、不受模型判断影响**的最终阻断，与内容安全管道里
 * 「确定性规则最终阻断」同一条线。词库可维护、可审计，比 prompt 约束可靠。
 */

/** 第一层判定结果 */
export type LexiconVerdict =
  | { kind: "in_domain"; matchedTerms: string[] }
  /** 命中红线 —— 无条件阻断，不进入第二层 */
  | { kind: "blocked"; category: BlockedCategory; matchedTerms: string[] }
  /** 没有命中任何领域词 —— 疑似脱离范畴，不进入第二层 */
  | { kind: "out_of_domain" };

export type BlockedCategory =
  /** 改变骨骼/脸型/五官比例 */
  | "facial_structure"
  /** 改变性别/年龄/种族 */
  | "identity_attribute"
  /** 变成某个具体真人 */
  | "impersonation"
  /** 身体部位增强 */
  | "body_enhancement";

