/** 返回命中的规范 tag，未命中返回 null（走"用户指定方向"路径，不是错误） */
export function normalizeToStyleTag(text: string): string | null {
  const lower = text.toLowerCase();
  for (const [canonical, aliases] of Object.entries(STYLE_TAG_ALIASES)) {
    if (aliases.some((a) => lower.includes(a.toLowerCase()))) return canonical;
  }
  return null;
}
